/** Раздел открыт: сама страница или вложенная. */
export const isActive = (pathname: string, item: Pick<NavItem, 'to' | 'also'>) =>
  [item.to, ...(item.also ?? [])].some((p) => pathname.startsWith(p));

/** Пункты «Ещё», видимые этой семье. */
export const moreFor = (admin: boolean) =>
  MORE.map((g) => ({ ...g, items: g.items.filter((it) => admin || !it.admin) }));
