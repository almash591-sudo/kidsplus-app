// 20 уроков «Счёт» (этап 49) — подготовка к школе: состав числа до 10, соседи числа до 20,
// знаки «больше, меньше, равно» и задачи. Темы чередуются, числа растут от урока к уроку.
// Условия задач читает совёнок: числа в них — словами, чтобы голос не ошибся с родом
// («две птички»). Картинки — эмодзи, файлы не нужны.
import { gameSpec, type GameSpec, type WordProblem } from './games';

export interface MathLesson {
  n: number;
  age: 'old';
  title: string;
  spec: GameSpec;
}

const house = (numbers: number[], rounds = 6): GameSpec => ({
  kind: 'numberHouse',
  numbers,
  dots: true,
  choices: 3,
  rounds,
});
const neighbors = (
  from: number,
  to: number,
  modes: ('gap' | 'before' | 'after')[],
  rounds = 6,
): GameSpec => ({ kind: 'numberNeighbors', from, to, modes, choices: 3, rounds });
const signs = (max: number, dots: boolean, rounds = 6): GameSpec => ({
  kind: 'compareSign',
  max,
  equal: true,
  dots,
  rounds,
});
type P = [emoji: string, a: number, op: '+' | '−', b: number, text: string];
const problems = (list: P[], rounds = 5): GameSpec => ({
  kind: 'wordProblem',
  problems: list.map(([emoji, a, op, b, text]): WordProblem => ({
    emoji,
    a,
    op: op === '+' ? 'plus' : 'minus',
    b,
    text,
  })),
  scene: true,
  choices: 3,
  rounds,
});

