// Фразы, которые ребёнок слышит в квизе (п. 5.4 ТЗ): спокойно, без наказывающих звуков.
// Род берётся из профиля ребёнка; озвучка генерируется один раз и кэшируется.
// Вариантов много (этап 30): ребёнок отвечает часто, и одна и та же фраза подряд надоедает —
// приложение выбирает фразу, которой не было среди последних.

/**
 * correct — верно; retry — неверно, ещё попытка; done — квиз пройден;
 * streak — несколько верных подряд; slow — тыкает наугад, пауза «не спеши».
 */
