// Книжки (этап 52): встроенная библиотека для раздела «Книжки». Только общественное достояние —
// народные сказки в записи Афанасьева, классика, умершие до 1954 года авторы и переводчики.
// Текст — с Викитеки (source), бережно сокращён для малышей: страшное смягчено, устаревшее —
// понятными словами. Картинки — глиняные сцены в детском приложении: /books/<сцена>.webp, их
// телефон не кладёт в установку, а качает при назначении книжки (как видео и озвучку).
import type { PoemChoice, PoemQuestion } from './poems';

export type { PoemChoice as BookChoice };

export interface BookPage {
  /**
   * Предложения страницы (1–3): голос читает их по одному и подсвечивает то, что звучит. Каждое —
   * одна фраза озвучке, не длиннее 200 знаков; ударение — «+» перед гласной (как в фразах).
   */
  text: string[];
  /** Сцена страницы (ключ из art); соседние страницы делят сцену — камера наезжает по-другому. */
  picture: string;
  /**
   * «Прочитай сам» (у книжек старшим): слово из текста страницы — как в тексте, без ударений.
   * Перед чтением оно крупно по слогам; ребёнок читает и нажимает — голос говорит слово.
   */
  read?: string;
}

export interface BookChapter {
  /** Название главы — у длинных книжек; у короткой одна глава без названия. */
  title?: string;
  pages: BookPage[];
  /** Вопросы в конце главы, ответ — картинкой. */
  questions: PoemQuestion[];
}

export type BookGenre = 'folk' | 'tale' | 'story';

export interface Book {
  title: string;
  /** Автор; у народных — null. */
  author: string | null;
  /** Переводчик (виден в кабинете, вслух не звучит). */
  translator?: string;
  genre: BookGenre;
  /** С какого возраста (лет) — подсказка в кабинете и назначение по возрасту. */
  fromAge: number;
  /** Обложка на полке — одна из сцен. */
  cover: string;
  /**
   * Сцены книжки: ключ → эмодзи, которыми сцена видна, пока её не нарисовали (drawn: false), и
   * подпись для озвучки в тестах.
   */
  art: Record<string, string>;
  /** Сцены нарисованы и лежат в apps/kid/public/books/<ключ>.webp. */
  drawn: boolean;
  chapters: BookChapter[];
  /** Откуда текст и почему его можно брать. */
  source: { wikisource: string; note: string };
}

