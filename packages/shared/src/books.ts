export type BookCode = keyof typeof BOOKS;
export const BOOK_CODES = Object.keys(BOOKS) as [BookCode, ...BookCode[]];
export const bookOf = (code: BookCode): Book => BOOKS[code];

/** «Русская народная сказка «Репка».», «Дмитрий Мамин-Сибиряк. «Сказка про…».» — так книжка объявляется. */
export function bookAnnounce(b: Book): string {
  return b.genre === 'folk'
    ? `Русская народная сказка «${b.title}».`
    : `${b.author}. «${b.title}».`;
}

/** «Глава вторая. «Цветочек»» — для книжек с главами. */
const ORDINAL = [
  'первая',
  'вторая',
  'третья',
  'четвёртая',
  'пятая',
  'шестая',
  'седьмая',
  'восьмая',
];
export function chapterAnnounce(b: Book, chapter: number): string | null {
  if (b.chapters.length < 2) return null;
  const title = b.chapters[chapter]!.title;
  return `Глава ${ORDINAL[chapter] ?? chapter + 1}.${title ? ` «${title}».` : ''}`;
}

/** Путь картинки сцены в детском приложении. */
export const bookPicture = (scene: string) => `/books/${scene}.webp`;

/** Все картинки книжки — скачать заранее, чтобы читать без сети. Не нарисована — нечего качать. */
export const bookPictures = (b: Book): string[] =>
  b.drawn
    ? [...new Set([b.cover, ...b.chapters.flatMap((c) => c.pages.map((p) => p.picture))])].map(
        bookPicture,
      )
    : [];

/** Сколько знаков звучит в книжке — для оценки стоимости озвучки. */
export const bookChars = (b: Book) =>
  b.chapters.reduce((n, c) => n + c.pages.reduce((m, p) => m + p.text.join(' ').length, 0), 0);
