const VOWELS = ['А', 'О', 'У', 'Ы', 'И', 'Э'];
const IOTATED = ['Я', 'Ё', 'Ю', 'Е'];
const syl = (consonants: string[], vowels = ['А', 'О', 'У', 'Ы', 'И']) =>
  consonants.flatMap((c) => vowels.map((v) => c + v)).filter((s) => !/[КГХ]Ы|[ЖШ]Ы/.test(s));

const letter = (letters: string[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'letter',
  letters,
  choices,
  rounds,
});
const syllable = (syllables: string[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'syllable',
  syllables,
  choices,
  rounds,
});
const first = (words: W[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'firstLetter',
  words: w(words),
  choices,
  rounds,
});
const read = (words: W[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'readWord',
  words: w(words),
  choices,
  rounds,
});

