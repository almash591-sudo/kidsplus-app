const count = (words: W[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'syllableCount',
  words: w(words),
  choices,
  rounds,
});
const place = (sound: SoundLetter, rounds = 6): GameSpec => ({
  kind: 'soundPlace',
  sound,
  words: w(SOUND_WORDS[sound]!),
  rounds,
});
const scheme = (words: W[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'wordScheme',
  words: w(words),
  choices,
  rounds,
});
const pick = (items: P[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'pickWord',
  items: items.map(([emoji, word, similar]) => ({ emoji, word, similar: similar.split(' ') })),
  choices,
  rounds,
});
const phrase = (items: F[], choices = 3, rounds = 6): GameSpec => ({
  kind: 'readPhrase',
  items: items.map(([text, emoji, similar]) => ({ text, emoji, similar: similar.split(' ') })),
  choices,
  rounds,
});

