/** Звонкие в конце слога оглушаются («аб» звучит как «ап») — с ними только прямые слоги. */
const VOICED_PAIRED = 'БВГДЖЗ';
/** Слоги «Прочитай»: МА, МО, МУ и АМ, ОМ, УМ — с гласными, которые уже знают (О, А, У). */
function gardenSyllables(l: string): string[] {
  if (l === 'Й') return OAU.map((v) => v + l);
  if ([...VOWELS, ...IOTATED, 'Ъ', 'Ь'].includes(l)) return [];
  return [...OAU.map((v) => l + v), ...(VOICED_PAIRED.includes(l) ? [] : OAU.map((v) => v + l))];
}

/** Ъ и Ь — знаки, а не буквы: «обведи большой знак», «шарики с мягким знаком». */
const SIGN_WITH: Record<string, string> = { Ъ: 'твёрдым знаком', Ь: 'мягким знаком' };

export interface GardenLesson {
  title: string;
  spec: GameSpec;
}

/**
 * Блок уроков «Буквы из садика» для одной буквы — как «Повторяем О, А, У»: обвести большую
 * (ступенями), найти среди похожих, услышать звук, первая буква слова, обвести маленькую,
 * шарики, прочитать слоги, написать без подсказки. Каких-то уроков у буквы нет: у Ь нет ни
 * звука, ни слов на эту букву. А, О, У — общим блоком 61–70.
 */
export function gardenLessons(l: string): GardenLesson[] {
  if (GARDEN_OAU.includes(l))
    return LETTER_LESSONS.slice(60, 70).map(({ title, spec }) => ({ title, spec }));
  if (!GARDEN_LETTERS.includes(l)) return [];
  const big = l as TraceLetter;
  const small = l.toLowerCase() as TraceLetter;
  const sign = SIGN_WITH[l];
  const steps: [string, GameSpec][] = [
    [
      sign ? 'обведи большой знак' : 'обведи большую букву',
      { kind: 'tracing', shapes: [big], guides: ['dots', 'line', 'start'] },
    ],
    [
      'найди среди похожих',
      {
        kind: 'letter',
        letters: [l, ...SIMILAR[l]!],
        ask: [l],
        choices: 3,
        rounds: 8,
        letterCase: 'mixed',
      },
    ],
  ];
  if (SOUND_WORDS[l as SoundLetter]) steps.push([`где звук ${l}?`, place(l as SoundLetter, 8)]);
  const words = GARDEN_FIRST[l];
  if (words) steps.push(['с какой буквы?', first(words, 3, 6)]);
  steps.push(
    [
      sign ? 'обведи маленький знак' : 'обведи маленькую букву',
      { kind: 'tracing', shapes: [small], guides: ['dots', 'line', 'start'] },
    ],
    [
      `шарики с ${sign ?? `буквой ${l}`}`,
      {
        kind: 'balloons',
        count: 6,
        target: null,
        letters: { find: l, others: SIMILAR[l]!, lower: true },
      },
    ],
  );
  const syllables = gardenSyllables(l);
  if (syllables.length) steps.push(['прочитай слоги', syllable(syllables, 3, 6)]);
  steps.push([
    'напиши без подсказки',
    { kind: 'tracing', shapes: [big, small], guides: ['start'] },
  ]);
  return steps.map(([topic, s]) => ({
    title: `${GARDEN_TITLE} · ${l}: ${topic}`,
    spec: gameSpec.parse(s),
  }));
}
