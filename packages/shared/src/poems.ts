// Стихи и сказки (этап 45): встроенная библиотека для раздела «Стихи и сказки». Только народное и
// классика в общественном достоянии (Барто, Маршак, Чуковский, Михалков — ещё под авторским
// правом, их здесь нет). Картинки — глиняные сцены в детском приложении: /poems/<picture>.webp.

/** Вариант ответа: слово (звучит голосом) и картинка — эмодзи или глиняная картинка (латиницей). */
export type PoemChoice = readonly [word: string, picture: string];

export interface PoemPart {
  /** Строки части; звучит часть целиком под своей картинкой. */
  lines: string[];
  picture: string;
}

/** «Договори словечко»: голос читает cue и замолкает — ребёнок выбирает word по картинке. */
export interface PoemBlank {
  /** Текст до слова, как в произведении (может захватывать прошлую строку). */
  cue: string;
  word: string;
  picture: string;
  /** Неверные варианты (рифмы и похожее — так интереснее и полезнее). */
  wrong: PoemChoice[];
}

/** Вопрос по смыслу: ответ — картинкой. */
export interface PoemQuestion {
  text: string;
  answer: PoemChoice;
  wrong: PoemChoice[];
}

export type PoemGenre = 'nursery' | 'poem' | 'fable' | 'tale';

export interface Poem {
  title: string;
  /** Автор; у народных — null. */
  author: string | null;
  genre: PoemGenre;
  /** С какого возраста (лет) — для подсказки в кабинете и назначения по возрасту. */
  fromAge: number;
  parts: PoemPart[];
  /**
   * Что учим наизусть: группы строк, по группе за занятие. У стихов — сам стих частями, у сказки —
   * присказка («Тянут-потянут…»), которую ребёнок повторяет.
   */
  learn: string[][];
  blanks: PoemBlank[];
  questions: PoemQuestion[];
}

