export type PoemCode = keyof typeof POEMS;
export const POEM_CODES = Object.keys(POEMS) as [PoemCode, ...PoemCode[]];
export const poemOf = (code: PoemCode): Poem => POEMS[code];

/** Глиняная картинка — латиницей; остальное — эмодзи. */
export const isClayPicture = (picture: string) => /^[a-z0-9-]+$/.test(picture);

/** «Стихотворение «Осень наступила». Алексей Плещеев.» — так произведение объявляется голосом. */
export function poemAnnounce(p: Poem): string {
  const genre = p.genre === 'tale' && !p.author ? 'Русская народная сказка' : GENRE_WORD[p.genre];
  return `${genre} «${p.title}».${p.author ? ` ${p.author}.` : ''}`;
}

/** Слова без знаков препинания, ё = е, в нижнем регистре — чтобы сравнивать тексты. */
export const poemWords = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\s-]|(?<!\p{L})-|-(?!\p{L})/gu, ' ')
    .split(/\s+/)
    .filter(Boolean);

/** Части целиком (как одна фраза голосу, если не длиннее limit), иначе — по строкам. */
export function partSpeech(part: PoemPart, limit = 200): string[] {
  const whole = part.lines.join('\n');
  return whole.length <= limit ? [whole] : part.lines;
}

/** В какой части произведения стоит слово «Договори» (под её картинкой звучит ответ). */
export function blankPart(p: Poem, b: PoemBlank): number {
  const want = [...poemWords(b.cue), ...poemWords(b.word)];
  const words: { w: string; part: number }[] = p.parts.flatMap((part, i) =>
    part.lines.flatMap((l) => poemWords(l).map((w) => ({ w, part: i }))),
  );
  for (let i = 0; i + want.length <= words.length; i++) {
    if (want.every((w, k) => words[i + k]!.w === w)) return words[i + want.length - 1]!.part;
  }
  return -1;
}

/**
 * Какие «Договори» уже можно спрашивать: выучено групп `learned` (и учим следующую). Слово из ещё
 * не начатой группы ждёт; слово, которого в заучивании нет (сказка), — можно всегда.
 */
export function blanksFor(p: Poem, learned: number): PoemBlank[] {
  const text = (groups: string[][]) => ` ${poemWords(groups.flat().join(' ')).join(' ')} `;
  const open = text(p.learn.slice(0, learned + 1));
  const all = text(p.learn);
  return p.blanks.filter((b) => {
    const phrase = ` ${[...poemWords(b.cue), ...poemWords(b.word)].join(' ')} `;
    return open.includes(phrase) || !all.includes(phrase);
  });
}

/** Начало строки для «Расскажи вместе со мной»: первое слово (короткое — с соседним). */
export function lineStart(line: string): string {
  const words = line.split(/\s+/).filter(Boolean);
  const take = words[0]!.replace(/[^\p{L}-]/gu, '').length <= 3 && words.length > 2 ? 2 : 1;
  return `${words
    .slice(0, take)
    .join(' ')
    .replace(/[,.!?;:—-]+$/u, '')}…`;
}
