// Черновик учебного плана (п. 6.1 ТЗ): темы по неделям для каждого предмета.
// В модель уходят только возраст, предметы и число недель — без имени и других данных ребёнка.

export const CURRICULUM_DRAFT_VERSION = 'curriculum-draft.v1';

export function curriculumDraftPrompt(input: {
  ageYears: number;
  weeks: number;
  /** Предметы: код (для ответа) и название по-русски. */
  subjects: { code: string; label: string }[];
}): string {
  const list = input.subjects.map((s) => `- ${s.code}: ${s.label}`).join('\n');
  return `Ты — методист раннего развития. Составь учебный план для ребёнка ${input.ageYears} лет на ${input.weeks} недель.
Занятия короткие (около 20 минут в день на предмет): видео 1–5 минут, карточки со словами и картинками, простые игры.

Предметы (в ответе указывай код предмета):
${list}

Для каждой недели от 1 до ${input.weeks} и для каждого предмета — ровно одна тема.
Требования к темам:
- по возрасту: для 2–3 лет — самое простое и конкретное (животные, цвета, формы, счёт до 3–5), для 4–6 лет — сложнее (счёт до 10–20, буквы, звуки, простые слова, сравнение, природные явления);
- от простого к сложному, раз в 3–4 недели — неделя повторения;
- название темы по-русски, коротко (2–5 слов), понятно родителю: «Счёт до 5», «Цвета: красный и синий», «Животные Африки»;
- для английского и китайского — темы словаря, название по-русски («Фрукты по-английски»);
- без опасного, пугающего и рекламного.

Ответ — только JSON по схеме: {"topics": [{"subject": "<код>", "week": <номер>, "title": "<тема>"}]}.`;
}
