// Сказка на ночь (этап 31): короткая, спокойная, по теме родителя.
// В модель уходят только тема и возраст — без имени и других данных ребёнка.

export const BEDTIME_STORY_VERSION = 'bedtime-story.v1';

export function bedtimeStoryPrompt(input: { ageYears: number; theme: string }): string {
  return `Ты — детский писатель. Напиши сказку на ночь по-русски для ребёнка ${input.ageYears} лет.
Тема от родителя: «${input.theme}».

Требования:
- длина 300–450 слов (2–4 минуты чтения вслух), 5–8 абзацев, в абзаце 2–5 коротких предложений;
- спокойная и добрая: без страшного, злодеев, опасностей, драк, болезней, смерти и рекламы; если тема пугающая — поверни её к уюту и безопасности;
- герои — зверята, игрушки, природа; без имён настоящих людей и без обращения к ребёнку по имени;
- простые слова по возрасту, повторы и ритм, мягкие звуки («тихо-тихо», «ш-ш-ш»);
- темп к концу замедляется: герои укладываются спать, последний абзац — пожелание спокойной ночи слушателю;
- текст будет читать голос: без смайликов, списков, заголовков внутри, ремарок и звёздочек;
- название — 2–6 слов.

Ответ — только JSON по схеме: {"title": "<название>", "paragraphs": ["<абзац>", ...]}.`;
}
