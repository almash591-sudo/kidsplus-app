// Пояснение к вопросу квиза (этап 39): совёнок говорит его ребёнку после верного ответа.
// В модель уходят только текст вопроса и подписи вариантов (их пишет родитель) — без данных ребёнка.

export const QUIZ_EXPLANATION_VERSION = 'quiz-explanation.v1';

export function quizExplanationPrompt(input: {
  question: string;
  correct: string;
  wrong: string[];
}): string {
  const wrong = input.wrong.length ? input.wrong.map((w) => `«${w}»`).join(', ') : 'нет';
  return `Ты — воспитатель детского сада. Ребёнок 2–6 лет посмотрел короткое видео и ответил на вопрос, выбрав картинку.

Вопрос: «${input.question}»
Верный ответ: «${input.correct}»
Другие варианты: ${wrong}

Ребёнок ответил верно. Совёнок сначала скажет «Это ${input.correct}.», а потом — твоё пояснение.
Напиши пояснение: почему верно именно это, чтобы ребёнок запомнил.
Требования:
- по-русски, 1–2 очень коротких предложения, всего не больше 150 символов;
- простыми словами, которые понимает малыш; конкретный признак («Кошка говорит „мяу“»);
- не повторяй «Это ${input.correct}», не хвали («молодец» уже прозвучало), без вопросов к ребёнку;
- без цифр и сокращений — текст читает синтезатор речи; без эмодзи;
- без пугающего и без выдуманных фактов; если не уверен — опиши, как выглядит верный ответ.

Ответ — только JSON по схеме: {"explanation": "..."}.`;
}
