// Анализ видео для модерации (п. 7.1 ТЗ). Версия в имени файла; при изменении — новый файл.
// В шаблон не попадают имена и данные детей — только возраст и тема.

export const MODERATE_VIDEO_VERSION = 'moderate-video.v1';

export interface ModerateVideoVars {
  /** Возраст детей, например «2 и 5 лет». */
  ages: string;
  /** Подсказка родителя о теме или пустая строка. */
  topic: string;
  title: string;
  channel: string;
  durationSec: number;
  madeForKids: string;
  description: string;
}

export function moderateVideoPrompt(v: ModerateVideoVars): string {
  return `Ты помогаешь родителю отбирать видео YouTube для детей ${v.ages}. Посмотри видео целиком (картинку и звук) и подготовь отчёт для модерации. Решение принимает родитель — твоя задача честно показать риски и предложить учебные фрагменты.

Данные видео:
- Название: ${v.title}
- Канал: ${v.channel}
- Длительность: ${v.durationSec} с
- Отмечено автором «для детей»: ${v.madeForKids}
- Тема, которую ищет родитель: ${v.topic || 'не указана'}
- Описание (начало): ${v.description || '—'}

Что оценить:
1. summary — о чём видео, 2–4 предложения по-русски.
2. ages — подходит ли видео для групп 2-3, 4-5 и 6 лет (good/ok/bad) с короткой причиной.
3. educationalValue — польза от 1 до 5 и почему.
4. redFlags — всё тревожное с временем (ММ:СС): пугающее, насилие, грубая лексика, распаковки игрушек и реклама, кликбейт, гиперстимуляция (слишком быстрый монтаж, крики, мельтешение), ошибки в материале, неправильное произношение в языковых видео. Нет флагов — пустой список. Не выдумывай.
5. recommendation — approve (можно смело), review (нужно посмотреть родителю), reject (не подходит).
6. segments — до 6 самодостаточных фрагментов длиной от 1 до 5 минут, не пересекаются, в пределах видео. Время start/end — реальное, по тому, что ты видел и слышал. Если видео не подходит детям — пустой список.
   Для каждого фрагмента 3–10 вопросов квиза для самого младшего возраста, о том, что было именно в этом фрагменте:
   - prompt — короткий вопрос для озвучки ребёнку, например «Где кошка?», «Какого цвета был шарик?», «Сколько было уточек?»;
   - lang — ru; для видео на английском или китайском, где ребёнок учит язык, вопрос можно задать на языке видео (en/zh), если он очень простой;
   - ровно 4 варианта-картинки, один верный (correct: true). label — подпись для родителя, picture — что нарисовано, emoji — один эмодзи, точно изображающий вариант (🐱, 🔴, 3️⃣), или пустая строка, если подходящего нет;
   - неверные варианты — правдоподобные, но однозначно неверные; без подвохов.

Пиши по-русски (кроме вопросов на языке видео). Ответ — только JSON по схеме.`;
}
